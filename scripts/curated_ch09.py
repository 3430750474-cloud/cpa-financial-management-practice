def pvifa(rate: float, periods: int) -> float:
    return (1 - (1 + rate) ** -periods) / rate


def ytm(face: float, coupon: float, years: int, price: float) -> float:
    low, high = 0.0, .30
    for _ in range(100):
        rate = (low + high) / 2
        value = sum(face * coupon / (1 + rate) ** t for t in range(1, years + 1)) + face / (1 + rate) ** years
        if value > price:
            low = rate
        else:
            high = rate
    return (low + high) / 2


